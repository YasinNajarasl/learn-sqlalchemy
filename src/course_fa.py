def localize(course):
    for lesson, content in zip(course["lessons"], LESSONS, strict=True):
        lesson.update(zip(("title", "goal", "explanation", "exercise", "hint"), content))
        lesson["category"] = CATEGORIES[lesson["category"]]
        lesson["level"] = LEVELS[lesson["level"]]
        lesson["slides"] = lesson["slides"].replace("slides", "اسلاید").replace("slide", "اسلاید")
    for group in course["categories"]:
        group["name"] = CATEGORIES[group["name"]]
    return course
