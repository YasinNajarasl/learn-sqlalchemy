function selectLesson(index, scroll = false) {
  if (!state.course) return;
  const bounded = Math.max(0, Math.min(index, state.course.lessons.length - 1));
  state.activeLesson = bounded;
  localStorage.setItem(CURRENT_LESSON_KEY, String(bounded));
  renderLessonNav();
  renderLesson(bounded);
  if (scroll && window.innerWidth < 1000) {
    document.getElementById('lesson-card')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }
}

function showLabTab(tab) {
  state.labTab = tab;
  document.querySelectorAll('[data-lab-tab]').forEach((button) => {
    button.classList.toggle('active', button.dataset.labTab === tab);
  });
  const output = document.getElementById('lab-output');
  const sqlPanel = document.getElementById('lab-sql-panel');
  if (output) output.hidden = tab !== 'output';
  if (sqlPanel) sqlPanel.hidden = tab !== 'sql';
}

function renderLabResult(data) {
  const output = document.getElementById('lab-output');
  const status = document.getElementById('lab-status');
  const sqlPre = document.getElementById('lab-sql');
  const count = document.getElementById('lab-sql-count');
  let text = data.stdout || '';
  if (data.stderr) text += `${text ? '\n' : ''}${data.stderr}`;
  if (data.error) text += `${text ? '\n\n' : ''}${data.error}`;
  if (output) {
    output.textContent = text || '(no output)';
    output.classList.toggle('error', Boolean(data.error));
  }
  if (status) {
    status.textContent = `${uiText(data.error ? 'Error' : 'Done')} · ${data.duration_ms} ms · ${uiText(data.mode)}`;
    status.className = `lab-status ${data.error ? 'error' : 'success'}`;
  }
  const statements = data.sql || [];
  if (count) count.textContent = String(statements.length);
  if (sqlPre) {
    sqlPre.textContent = statements.length
      ? statements
          .map((query, index) => {
            const params = query.params && query.params !== '()' ? `\n-- params: ${query.params}` : '';
            return `-- ${index + 1}\n${query.sql}${params}`;
          })
          .join('\n\n')
      : 'No statements captured.';
  }
  if (data.error) showLabTab('output');
}

async function runLab() {
  const editor = document.getElementById('lab-code');
  const button = document.getElementById('btn-run-lab');
  const status = document.getElementById('lab-status');
  if (!editor || !button) return;
  if (!editor.value.trim()) {
    showToast('Write some code first.', 'error');
    return;
  }
  const live = Boolean(document.getElementById('lab-live')?.checked);
  button.disabled = true;
  if (status) {
    status.textContent = 'Running…';
    status.className = 'lab-status running';
  }
  try {
    const { data } = await api('/lab/run', {
      method: 'POST',
      body: { code: editor.value, live },
    });
    renderLabResult(data);
    if (live) await loadSchema();
  } catch (error) {
    const output = document.getElementById('lab-output');
    if (output) {
      output.textContent = error.message;
      output.classList.add('error');
    }
    if (status) {
      status.textContent = 'Error';
      status.className = 'lab-status error';
    }
    showLabTab('output');
  } finally {
    button.disabled = false;
  }
}

async function loadSchema() {
  const body = document.getElementById('schema-body');
  if (!body) return;
  try {
    const { data } = await api('/lab/schema');
    const url = document.getElementById('schema-url');
    if (url) url.textContent = `${data.dialect} · ${data.url}`;
    body.innerHTML = data.tables
      .map((table) => {
        const rows = table.rows === null ? '?' : table.rows;
        const columns = table.columns
          .map((column) => {
            const foreign = (table.foreign_keys || []).find((key) => key.column === column.name);
            const marker = column.primary_key
              ? 'PK'
              : foreign
                ? `FK → ${foreign.references}`
                : column.nullable
                  ? ''
                  : 'NOT NULL';
            return `<tr><td><code>${esc(column.name)}</code></td><td>${esc(column.type)}</td><td class="schema-key">${esc(marker)}</td></tr>`;
          })
          .join('');
        return `
          <div class="schema-table">
            <div class="schema-head"><strong>${esc(table.name)}</strong><span>${rows} rows</span></div>
            <table class="schema-cols">
              <thead><tr><th>Column</th><th>Type</th><th>Key</th></tr></thead>
              <tbody>${columns}</tbody>
            </table>
          </div>`;
      })
      .join('');
    if (!data.tables.length) body.innerHTML = '<p class="hint">No tables found. Open the dashboard once to create the schema.</p>';
  } catch (error) {
    body.textContent = `Schema unavailable: ${error.message}`;
  }
}

function setupLearnPage() {
  const search = document.getElementById('lesson-search');
  search?.addEventListener('input', (event) => {
    state.lessonQuery = event.target.value;
    renderLessonNav();
  });

  document.getElementById('lesson-nav')?.addEventListener('click', (event) => {
    const button = event.target.closest('[data-lesson]');
    if (button) selectLesson(Number(button.dataset.lesson) - 1, true);
  });

  document.getElementById('btn-run-lab')?.addEventListener('click', runLab);
  document.getElementById('btn-refresh-schema')?.addEventListener('click', loadSchema);
  document.getElementById('btn-reset-code')?.addEventListener('click', () => {
    const lab = state.course?.lessons[state.activeLesson];
    if (lab) setLabCode(lab.starter);
  });
  document.getElementById('btn-solution-code')?.addEventListener('click', () => {
    const lab = state.course?.lessons[state.activeLesson];
    if (lab) setLabCode(lab.code);
  });
  document.getElementById('btn-copy-code')?.addEventListener('click', async () => {
    const editor = document.getElementById('lab-code');
    if (!editor) return;
    try {
      await navigator.clipboard.writeText(editor.value);
      showToast('Code copied.', 'success');
    } catch {
      editor.select();
      document.execCommand('copy');
      showToast('Code copied.', 'success');
    }
  });
  document.getElementById('btn-mark-complete')?.addEventListener('click', () => {
    const number = state.activeLesson + 1;
    if (state.completed.has(number)) state.completed.delete(number);
    else state.completed.add(number);
    saveCompletedLessons();
    updateLearnProgress();
    renderLessonNav();
    updateCompleteButton();
  });
  document.getElementById('btn-next-lesson')?.addEventListener('click', () => {
    selectLesson(state.activeLesson + 1, true);
  });
  document.getElementById('btn-reset-progress')?.addEventListener('click', () => {
    if (!confirmAction('Clear completed lessons in this browser?')) return;
    state.completed.clear();
    saveCompletedLessons();
    updateLearnProgress();
    renderLessonNav();
    updateCompleteButton();
  });
  document.getElementById('lab-live')?.addEventListener('change', (event) => {
    if (!event.target.checked) return;
    const accepted = confirmAction(
      'Live mode runs your code against the real database. Commits and deletes are permanent. Continue?'
    );
    if (!accepted) event.target.checked = false;
  });
  document.querySelectorAll('[data-lab-tab]').forEach((button) => {
    button.addEventListener('click', () => showLabTab(button.dataset.labTab));
  });

  const editor = document.getElementById('lab-code');
  editor?.addEventListener('input', () => {
    updateEditorGutter();
    state.drafts[state.activeLesson + 1] = editor.value;
    saveDrafts();
  });
  editor?.addEventListener('scroll', () => {
    const gutter = document.getElementById('lab-line-numbers');
    if (gutter) gutter.scrollTop = editor.scrollTop;
  });
  editor?.addEventListener('keydown', (event) => {
    if (event.key === 'Tab') {
      event.preventDefault();
      const start = editor.selectionStart;
      const end = editor.selectionEnd;
      editor.setRangeText('    ', start, end, 'end');
      updateEditorGutter();
    }
    if ((event.ctrlKey || event.metaKey) && event.key === 'Enter') {
      event.preventDefault();
      runLab();
    }
  });
}

async function loadWorkbook() {
  if (!state.course) {
    const { data } = await api(`/learn/workbook?lang=${uiLocale}`);
    state.course = data;
    state.completed = loadCompletedLessons();
    state.drafts = loadDrafts();
    const saved = Number(localStorage.getItem(CURRENT_LESSON_KEY));
    state.activeLesson = Number.isInteger(saved) ? Math.min(Math.max(saved, 0), data.lessons.length - 1) : 0;
    setupLearnPage();
    loadSchema();
  }
  selectLesson(state.activeLesson);
  updateLearnProgress();
}

async function loadSlideMap() {
  const body = document.getElementById('slide-map-body');
  if (!body) return;
  try {
    const { data } = await api('/static/slide_map.json');
    body.innerHTML = data
      .map(
        (slide) => `
        <tr>
          <td><span class="badge">${slide.slide}</span></td>
          <td><span class="cell-title">${esc(uiLocale === 'fa' ? slide.text.split('\n')[0] : slide.title)}</span></td>
          <td>${slide.file ? `<code>${esc(slide.file)}</code><div class="cell-sub">${esc(slide.symbol)} · lines ${slide.start}–${slide.end}</div>` : 'Overview / reference slide'}</td>
        </tr>`
      )
      .join('');
  } catch (error) {
    body.innerHTML = '<tr><td colspan="3" class="empty-cell">Slide map unavailable.</td></tr>';
  }
}

