function setSelectOptions(id, optionsHtml, keepValue = true) {
  const select = document.getElementById(id);
  if (!select) return;
  const current = select.value;
  select.innerHTML = optionsHtml;
  if (keepValue && current && [...select.options].some((option) => option.value === current)) {
    select.value = current;
  }
}

