async function loadUsers() {
  const params = new URLSearchParams();
  params.set('limit', state.users.limit);
  params.set('offset', state.users.offset);
  const q = val('users-q');
  const minAge = val('users-min-age');
  const maxAge = val('users-max-age');
  const domain = val('users-domain');
  const sortBy = val('users-sort') || 'id';
  const order = val('users-order') || 'asc';
  if (q) params.set('q', q);
  if (minAge) params.set('min_age', minAge);
  if (maxAge) params.set('max_age', maxAge);
  if (domain) params.set('email_domain', domain);
  params.set('sort_by', sortBy);
  params.set('order', order);

  const { data, headers } = await api(`/users/?${params.toString()}`);
  state.users.items = data;
  state.users.total = Number(headers.get('X-Total-Count') || data.length);
  renderUsers();
  renderPagination('users-pagination', state.users, loadUsers);
  setText('users-count-label', `${state.users.total} user${state.users.total === 1 ? '' : 's'}`);
  await loadAllUsers();
}

function renderUsers() {
  const body = document.getElementById('users-table-body');
  if (!state.users.items.length) {
    body.innerHTML = '<tr><td colspan="7" class="empty-cell">No users match these filters.</td></tr>';
    return;
  }
  body.innerHTML = state.users.items
    .map((user) => {
      const bio = user.bio ? (user.bio.length > 46 ? `${user.bio.slice(0, 46)}…` : user.bio) : '—';
      return `
        <tr>
          <td class="muted">${user.id}</td>
          <td><span class="cell-title">${esc(user.name)}</span></td>
          <td>${esc(user.email)}</td>
          <td>${user.age}</td>
          <td class="muted">${esc(bio)}</td>
          <td class="muted">${esc(formatDate(user.created_at))}</td>
          <td>
            <div class="inline-actions">
              <button class="btn btn-small btn-ghost" type="button" data-action="view" data-id="${user.id}">View</button>
              <button class="btn btn-small btn-ghost" type="button" data-action="age" data-id="${user.id}">Age</button>
              <button class="btn btn-small btn-danger-ghost" type="button" data-action="delete" data-id="${user.id}">Delete</button>
            </div>
          </td>
        </tr>`;
    })
    .join('');
}

