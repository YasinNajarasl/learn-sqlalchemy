const uiLocale = localStorage.getItem('yasin-lab-language') === 'fa' ? 'fa' : 'en';
function uiText(source) {
  if (uiLocale !== 'fa' || typeof source !== 'string') return source;
  const key = source.trim().replace(/\s+/g, ' ');
  if (Object.hasOwn(persian, key)) return persian[key];
  for (const [pattern, replacement] of [
    [/^slides? (.+)$/i, 'اسلاید $1'], [/^DB ready · (.+)$/, 'پایگاه داده آماده · $1'],
    [/^(\d+) users?$/, '$1 کاربر'], [/^(\d+) posts?$/, '$1 پست'], [/^(\d+) tags?$/, '$1 برچسب'],
    [/^(\d+) rows$/, '$1 ردیف'], [/^Showing (.+) of (.+)$/, 'نمایش $1 از $2'],
    [/^Delete (.+) and all of their posts\?$/, 'کاربر $1 و همهٔ پست‌هایش حذف شوند؟'],
    [/^Delete posts by authors older than (\d+)\?$/, 'پست‌های نویسندگان بالای $1 سال حذف شوند؟'],
    [/^Update age · (.+)$/, 'ویرایش سن · $1'], [/^User #(\d+)$/, 'کاربر شمارهٔ $1'], [/^Post #(\d+)$/, 'پست شمارهٔ $1'],
    [/^Inserted (\d+) users\.$/, '$1 کاربر درج شد.'], [/^Updated (\d+) users\.$/, '$1 کاربر تغییر کرد.'],
    [/^Deleted (\d+) posts\.$/, '$1 پست حذف شد.'],
  ]) if (pattern.test(key)) return key.replace(pattern, replacement);
  return source;
}

// Localize individual text nodes so controls nested in labels remain intact.
// Generated table rows, user content, editable code and SQL output are data.
const dynamicChrome = 'button,h2,h4,.field,.empty,.empty-cell,.detail-label,.page-info,.loading-label,.modal-footer,.hint,summary,th,.schema-head span,option[value=""],#page-title,#page-subtitle,#breadcrumb-page,#lab-status,#lesson-level,#db-status-text,#users-count-label,#posts-count-label,#tag-count-badge';
function translateTree(root, initial = false) {
  if (root.nodeType === Node.TEXT_NODE) {
    if (root.parentElement?.matches(dynamicChrome)) replaceCopy(root);
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  const elements = [root, ...root.querySelectorAll(initial ? '*' : dynamicChrome)];
  for (const el of elements) {
    if (el.closest('script,code,kbd,#ui-language')) continue;
    if (!initial && !el.matches(dynamicChrome)) continue;
    for (const child of el.childNodes) if (child.nodeType === Node.TEXT_NODE) replaceCopy(child);
    for (const attr of ['aria-label','placeholder','title']) {
      if (el.hasAttribute(attr)) el.setAttribute(attr, uiText(el.getAttribute(attr)));
    }
  }
}
function replaceCopy(node) {
  const old = node.data, translated = uiText(old);
  if (old !== translated) node.data = old.replace(old.trim(), () => translated);
}
function setupLanguage() {
  document.documentElement.lang = uiLocale;
  document.documentElement.dir = uiLocale === 'fa' ? 'rtl' : 'ltr';
  document.title = uiText('Yasin’s SQLAlchemy Lab');
  const select = document.getElementById('ui-language');
  select.value = uiLocale;
  select.onchange = () => {
    localStorage.setItem('yasin-lab-language', select.value);
    sessionStorage.setItem('yasin-lab-return-page', state.page);
    location.reload();
  };
  if (uiLocale !== 'fa') return;
  translateTree(document.body, true);
  document.getElementById('atomic-title').value = uiText('A transactional post');
  new MutationObserver(records => {
    for (const record of records) for (const node of record.addedNodes) translateTree(node);
  }).observe(document.body, {subtree:true, childList:true});
}
